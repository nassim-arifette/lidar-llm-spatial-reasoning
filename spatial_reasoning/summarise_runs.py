"""One page of tables from the November 2026 runs, read from their saved rows.

Every number is recomputed from ``rows_*.jsonl``; nothing is typed in. A run
that is absent is left out of its table rather than shown as a blank, and the
page lists what it found.

    python -m spatial_reasoning.summarise_runs
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List, Optional

from .drive_bootstrap import across, analyse

MODELS = (("1p5b", "Qwen2.5 1.5B"), ("7b", "Qwen2.5 7B"), ("32b", "Qwen2.5 32B (int4)"))
ARCHIVE = {"1p5b": "llm_modes", "7b": "llm_modes_7b", "32b": "llm_modes_32b"}


def rows_of(folder: Path, split: str) -> Optional[List[dict]]:
    path = folder / f"rows_{split}.jsonl"
    if not path.exists():
        return None
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()
            if line.strip()]


def acc(rows: Optional[List[dict]], mode: str) -> Optional[float]:
    if not rows:
        return None
    return sum(bool(r[f"{mode}_correct"]) for r in rows) / len(rows)


def fmt(value: Optional[float]) -> str:
    return "—" if value is None else f"{value:.3f}"


def ci(entry: Dict[str, float], signed: bool = False) -> str:
    sign = "+" if signed else ""
    return (f"{entry['estimate']:{sign}.3f} [{entry['low']:{sign}.3f}, "
            f"{entry['high']:{sign}.3f}]")


def tokens(rows: Optional[List[dict]]) -> str:
    if not rows:
        return "—"
    return f"{sum(r['direct_output_tokens'] for r in rows) / len(rows):.0f}"


def unread(rows: Optional[List[dict]]) -> str:
    if not rows:
        return "—"
    return str(sum(r["direct_answer"] is None for r in rows))


def build(results: Path, runs: Path) -> str:
    rescored = results / "rescored_as_labelled"
    found: List[str] = []

    def get(name: str, split: str = "eval") -> Optional[List[dict]]:
        rows = rows_of(runs / name, split)
        if rows is not None:
            found.append(f"{name} ({split}, n={len(rows)})")
        return rows

    out = ["# Runs of November 2026", "",
           "Generated by `python -m spatial_reasoning.summarise_runs` from the saved "
           "rows in this folder. Greedy decoding throughout. Refusals, invalid "
           "programs and unreadable answers count as wrong.", ""]

    # ------------------------------------------------------------------ #
    out += ["## 1. First comparison, evaluation split (200 questions, 3 drives)", "",
            "`direct-1` states the published signed sectors; `direct-2` states the "
            "convention the labels follow. The `r` variants ask for the working and "
            "read a final `Answer:` line (budget 2,048 tokens, chosen on development). "
            "The program columns are the same generations executed under each layout.", "",
            "| model | direct-1 | direct-2 | direct-1r | direct-2r | program, published "
            "layout | program, as labelled | program, as labelled, constrained |",
            "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for key, label in MODELS:
        archived = rows_of(results / ARCHIVE[key], "eval")
        relabelled = rows_of(rescored / ARCHIVE[key], "eval")
        d2 = get(f"d2_bare_{key}_eval")
        out.append(
            f"| {label} | {fmt(acc(archived, 'direct'))} | {fmt(acc(d2, 'direct'))} | "
            f"{fmt(acc(get(f'd1r_{key}_eval'), 'direct'))} | "
            f"{fmt(acc(get(f'd2r_{key}_eval'), 'direct'))} | "
            f"{fmt(acc(archived, 'executed'))} | {fmt(acc(relabelled, 'executed'))} | "
            f"{fmt(acc(get(f'c_{key}_eval'), 'executed'))} |")
        if d2 and relabelled:
            same = sum(a["program_raw"] == b["program_raw"] for a, b in zip(d2, relabelled))
            out.append(f"| | | | | | | *new run: {fmt(acc(d2, 'executed'))}; "
                       f"{same}/{len(d2)} programs identical to the archive* | |")
    out += ["", "Reasoned direct mode, in detail:", "",
            "| model | prompt | split | accuracy | mean output tokens | no readable answer |",
            "|---|---|---|---:|---:|---:|"]
    for key, label in MODELS:
        for prompt, name, split in (
                ("direct-1r", f"d1r_{key}_dev_v3", "dev"), ("direct-2r", f"d2r_{key}_dev_v3", "dev"),
                ("direct-1r", f"d1r_{key}_eval", "eval"), ("direct-2r", f"d2r_{key}_eval", "eval")):
            rows = get(name, split)
            if rows:
                out.append(f"| {label} | {prompt} | {split} | {fmt(acc(rows, 'direct'))} | "
                           f"{tokens(rows)} | {unread(rows)} |")

    # ------------------------------------------------------------------ #
    out += ["", "## 2. Validation drives (1,460 questions, 146 drives never used before)", "",
            "*Published conventions*: signed sectors, the ten named classes, prompt "
            "`direct-1`. *As labelled*: unsigned angle, every annotation and the ego "
            "vehicle count as things, prompt `direct-2`. Each cell is a separate run "
            "of both modes. Intervals are 95%, from 10,000 resamples of drives.", "",
            "| model | conventions | direct | program | program − direct | drives where "
            "program is ahead / behind / tied |", "|---|---|---:|---:|---:|---:|"]
    val: Dict[str, Dict[str, List[dict]]] = {}
    for key, label in MODELS:
        for tag, name in (("published", f"val_old_{key}"), ("as labelled", f"val_new_{key}")):
            rows = get(name)
            if not rows:
                continue
            val.setdefault(key, {})[tag] = rows
            a = analyse(rows)
            d = a["paired_difference"]["executed_minus_direct"]
            out.append(
                f"| {label} | {tag} | {ci(a['accuracy']['direct'])} | "
                f"{ci(a['accuracy']['executed'])} | {ci(d, True)} | "
                f"{d['drives_where_second_is_ahead']} / {d['drives_where_first_is_ahead']}"
                f" / {d['drives_tied']} |")
    out += ["", "Effect of the conventions on the same questions (as labelled − published):",
            "", "| model | direct | program |", "|---|---:|---:|"]
    for key, label in MODELS:
        pair = val.get(key, {})
        if len(pair) == 2:
            d = across(pair["as labelled"], pair["published"])
            out.append(f"| {label} | {ci(d['direct'], True)} | {ci(d['executed'], True)} |")
    out += ["", "By family, as labelled:", "",
            "| model | family | n | direct | program |", "|---|---|---:|---:|---:|"]
    for key, label in MODELS:
        rows = val.get(key, {}).get("as labelled")
        if not rows:
            continue
        for family in sorted({r["family"] for r in rows}):
            group = [r for r in rows if r["family"] == family]
            out.append(f"| {label} | {family} | {len(group)} | "
                       f"{fmt(acc(group, 'direct'))} | {fmt(acc(group, 'executed'))} |")

    # ------------------------------------------------------------------ #
    out += ["", "## 3. Constrained decoding (a separate condition)", "",
            "Programs decoded under a JSON Schema whose categories, statuses, "
            "relations and function names are closed sets. Layout as labelled.", "",
            "| run | n | mode | free | constrained | invalid or ill-typed, free → "
            "constrained |", "|---|---:|---|---:|---:|---|"]

    def bad(rows: List[dict], status: str) -> int:
        return sum(r[status] not in ("ok", "refused") for r in rows)

    for key, label in MODELS:
        for split in ("dev", "eval"):
            free = (rows_of(runs / f"d2_bare_{key}_{split}", split))
            con = get(f"c_{key}_{split}", split)
            if free and con:
                out.append(f"| {label}, first comparison, {split} | {len(con)} | flat | "
                           f"{fmt(acc(free, 'executed'))} | {fmt(acc(con, 'executed'))} | "
                           f"{bad(free, 'program_status')} → {bad(con, 'program_status')} |")
    free, con = get("free_wide_1p5b_eval"), get("c_wide_1p5b_eval")
    if free and con:
        for mode, status, name in (("executed", "program_status", "flat"),
                                   ("functional", "functional_status", "typed")):
            out.append(f"| Qwen2.5 1.5B, wide scope, eval | {len(con)} | {name} | "
                       f"{fmt(acc(free, mode))} | {fmt(acc(con, mode))} | "
                       f"{bad(free, status)} → {bad(con, status)} |")

    # ------------------------------------------------------------------ #
    out += ["", "## 4. Development split (100 questions), used to choose prompts and budgets",
            "", "| model | direct-1 (archive) | direct-2 | program, as labelled |",
            "|---|---:|---:|---:|"]
    for key, label in MODELS:
        rows = get(f"d2_bare_{key}_dev", "dev")
        archived = rows_of(results / ARCHIVE[key], "dev")
        if rows:
            out.append(f"| {label} | {fmt(acc(archived, 'direct'))} | "
                       f"{fmt(acc(rows, 'direct'))} | {fmt(acc(rows, 'executed'))} |")

    out += ["", "## Runs read", ""] + [f"- {name}" for name in sorted(set(found))]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    here = Path(__file__).resolve().parent / "results"
    p.add_argument("--results", type=Path, default=here)
    p.add_argument("--runs", type=Path, default=here / "runs_2026_11")
    args = p.parse_args(argv)
    text = build(args.results, args.runs)
    (args.runs / "README.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
